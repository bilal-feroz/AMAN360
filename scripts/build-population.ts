// Regenerates the committed synthetic population: npx tsx scripts/build-population.ts
// Output: src/scenario/population.json (synthetic people only — no real personal data, no tokens).
import { readFileSync, writeFileSync } from "node:fs";
import { generateRecipients } from "@/scenario/recipients";
import { buildClosures, buildHazardGeometry } from "@/scenario/scenario";
import { SAFETY_POLICY } from "@/scenario/policy";

const buildings = JSON.parse(readFileSync("public/data/osm/buildings.geojson", "utf8"));
const hazard = buildHazardGeometry();
const recipients = generateRecipients({
  buildings,
  geo: {
    zone: hazard.geometry,
    closures: buildClosures(),
    boundaryUncertaintyM: SAFETY_POLICY.boundaryUncertaintyMeters,
    closureApproachM: SAFETY_POLICY.closureApproachMeters,
  },
  tokenFor: () => "",
});
const out = recipients.map(({ token: _t, ...rest }) => rest);
writeFileSync("src/scenario/population.json", JSON.stringify({ note: "SYNTHETIC POPULATION — generated by scripts/build-population.ts", recipients: out }));
console.log("wrote", out.length, "synthetic recipients");
